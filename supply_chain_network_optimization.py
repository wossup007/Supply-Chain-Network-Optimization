import pandas as pd

df = orders.copy()

# add cost of each plant
cost_map = dict(zip(wh_costs['plant'], wh_costs['cost_per_unit']))
df['plant_cost'] = df['historical_plant'].map(cost_map)

# capacity tracking
remaining_capacity = dict(zip(capacities['plant'], capacities['capacity']))

print("Data ready")
print("Total orders:", len(df))

def find_best_plant(product_id, remaining_capacity, product_plant, cost_map):
    # Plants that can make this product
    possible_plants = product_plant[product_plant['product_id'] == product_id]['plant'].tolist()

    best_plant = None
    best_cost = float('inf')

    for plant in possible_plants:
        if remaining_capacity.get(plant, 0) > 0:  # still capacity leftt
            cost = cost_map.get(plant, 999)
            if cost < best_cost:
                best_cost = cost
                best_plant = plant

    return best_plant

optimized_plants = []

for idx, row in df.iterrows():
    best = find_best_plant(
        product_id = row['product_id'],
        remaining_capacity = remaining_capacity,
        product_plant = product_plant,
        cost_map = cost_map
    )

    if best is not None:
        optimized_plants.append(best)
        remaining_capacity[best] -= 1   # reduced capacity
    else:
        # If no plant has capacity, keep the original plant
        optimized_plants.append(row['historical_plant'])

df['optimized_plant'] = optimized_plants

print("Assignment completed")

# calculate costs
df['historical_cost'] = df['units'] * df['historical_plant'].map(cost_map)
df['optimized_cost'] = df['units'] * df['optimized_plant'].map(cost_map)

